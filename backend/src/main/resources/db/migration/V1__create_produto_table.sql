-- Tabela Produto
CREATE TABLE IF NOT EXISTS produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(500),
    preco DECIMAL(10,2) NOT NULL CHECK (preco >= 0),
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('HAMBURGUER', 'CACHORRO_QUENTE', 'SALGADO', 'BEBIDA', 'PORCAO', 'ADICIONAL')),
    tempo_preparo_minutos INTEGER NOT NULL DEFAULT 0,
    disponivel BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_produto_categoria ON produto(categoria);
CREATE INDEX IF NOT EXISTS idx_produto_disponivel ON produto(disponivel);
CREATE INDEX IF NOT EXISTS idx_produto_nome ON produto(nome);