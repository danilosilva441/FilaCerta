-- Tabela CaixaDiario
CREATE TABLE IF NOT EXISTS caixa_diario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL UNIQUE,
    hora_abertura TIME NOT NULL,
    hora_fechamento TIME,
    valor_inicial DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (valor_inicial >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO', 'FECHADO')),
    total_dinheiro DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total_dinheiro >= 0),
    total_debito DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total_debito >= 0),
    total_credito DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total_credito >= 0),
    total_pix DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total_pix >= 0),
    total_fiado DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (total_fiado >= 0),
    total_pedidos INTEGER NOT NULL DEFAULT 0 CHECK (total_pedidos >= 0),
    total_cancelados INTEGER NOT NULL DEFAULT 0 CHECK (total_cancelados >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_caixa_status ON caixa_diario(status);
CREATE INDEX IF NOT EXISTS idx_caixa_data ON caixa_diario(data);