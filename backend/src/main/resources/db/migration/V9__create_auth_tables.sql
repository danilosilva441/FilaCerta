-- ============================================
-- TABELA DE CLIENTES
-- ============================================
CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    sobrenome VARCHAR(100) NOT NULL,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cliente_codigo ON cliente(codigo);
CREATE INDEX IF NOT EXISTS idx_cliente_ativo ON cliente(ativo);

-- ============================================
-- TABELA DE USUÁRIOS (DONO/FUNCIONÁRIO)
-- ============================================
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('DONO', 'FUNCIONARIO')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_usuario_username ON usuario(username);
CREATE INDEX IF NOT EXISTS idx_usuario_tipo ON usuario(tipo);

-- ============================================
-- TABELA DE SESSÕES DOS CLIENTES
-- ============================================
CREATE TABLE IF NOT EXISTS sessao_cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    token VARCHAR(64) NOT NULL UNIQUE,
    data_hora_inicio TIMESTAMP NOT NULL,
    data_hora_fim TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_sessao_cliente FOREIGN KEY (cliente_id) 
        REFERENCES cliente(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sessao_token ON sessao_cliente(token);
CREATE INDEX IF NOT EXISTS idx_sessao_cliente ON sessao_cliente(cliente_id);
CREATE INDEX IF NOT EXISTS idx_sessao_ativo ON sessao_cliente(ativo);