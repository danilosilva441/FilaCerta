-- Tabela Pedido
CREATE TABLE IF NOT EXISTS pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER NOT NULL,
    nome_cliente VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('LEVAR', 'COMER_AQUI')),
    origem VARCHAR(20) NOT NULL CHECK (origem IN ('QR_CODE', 'MANUAL')),
    status VARCHAR(20) NOT NULL DEFAULT 'RECEBIDO' CHECK (status IN ('RECEBIDO', 'PREPARANDO', 'PRONTO', 'ENTREGUE', 'CANCELADO')),
    status_pagamento VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO' CHECK (status_pagamento IN ('AGUARDANDO', 'PAGO', 'FIADO')),
    metodo_pagamento VARCHAR(20) CHECK (metodo_pagamento IN ('DINHEIRO', 'CARTAO_DEBITO', 'CARTAO_CREDITO', 'PIX', 'FIADO')),
    valor_total DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (valor_total >= 0),
    data_hora_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_hora_pronto TIMESTAMP,
    data_hora_entrega TIMESTAMP,
    data_hora_pagamento TIMESTAMP,
    observacao VARCHAR(300),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    caixa_diario_data DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE INDEX IF NOT EXISTS idx_pedido_status ON pedido(status);
CREATE INDEX IF NOT EXISTS idx_pedido_data ON pedido(data_hora_pedido);
CREATE INDEX IF NOT EXISTS idx_pedido_cliente ON pedido(nome_cliente);
CREATE INDEX IF NOT EXISTS idx_pedido_caixa_data ON pedido(caixa_diario_data);
CREATE INDEX IF NOT EXISTS idx_pedido_numero ON pedido(numero);
CREATE INDEX IF NOT EXISTS idx_pedido_status_pagamento ON pedido(status_pagamento);