-- Tabela Comanda
CREATE TABLE IF NOT EXISTS comanda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome_cliente VARCHAR(100) NOT NULL,
    mesa INTEGER,
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTA' CHECK (status IN ('ABERTA', 'FECHADA')),
    valor_total DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (valor_total >= 0),
    abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechamento TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tabela ComandaPedido
CREATE TABLE IF NOT EXISTS comanda_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comanda_pedido_comanda FOREIGN KEY (comanda_id) 
        REFERENCES comanda(id) ON DELETE CASCADE,
    CONSTRAINT fk_comanda_pedido_pedido FOREIGN KEY (pedido_id) 
        REFERENCES pedido(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_comanda_codigo ON comanda(codigo);
CREATE INDEX IF NOT EXISTS idx_comanda_status ON comanda(status);
CREATE INDEX IF NOT EXISTS idx_comanda_abertura ON comanda(abertura);
CREATE INDEX IF NOT EXISTS idx_comanda_pedido_comanda ON comanda_pedido(comanda_id);
CREATE INDEX IF NOT EXISTS idx_comanda_pedido_pedido ON comanda_pedido(pedido_id);