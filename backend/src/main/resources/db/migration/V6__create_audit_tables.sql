-- Tabela de Auditoria de Pedidos
CREATE TABLE IF NOT EXISTS audit_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    acao VARCHAR(50) NOT NULL,
    status_anterior VARCHAR(50),
    status_novo VARCHAR(50),
    usuario VARCHAR(100),
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao VARCHAR(500),

    CONSTRAINT fk_audit_pedido FOREIGN KEY (pedido_id) 
        REFERENCES pedido(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_audit_pedido_pedido ON audit_pedido(pedido_id);
CREATE INDEX IF NOT EXISTS idx_audit_pedido_data ON audit_pedido(data_hora);

-- Tabela de Auditoria de Comandas
CREATE TABLE IF NOT EXISTS audit_comanda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id BIGINT NOT NULL,
    acao VARCHAR(50) NOT NULL,
    usuario VARCHAR(100),
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao VARCHAR(500),

    CONSTRAINT fk_audit_comanda FOREIGN KEY (comanda_id) 
        REFERENCES comanda(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_audit_comanda_comanda ON audit_comanda(comanda_id);