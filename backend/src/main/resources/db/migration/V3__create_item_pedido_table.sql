-- Tabela ItemPedido
CREATE TABLE IF NOT EXISTS item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario DECIMAL(10,2) NOT NULL CHECK (preco_unitario >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'PREPARANDO', 'PRONTO')),
    observacao_item VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) 
        REFERENCES pedido(id) ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_produto FOREIGN KEY (produto_id) 
        REFERENCES produto(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_item_pedido_pedido ON item_pedido(pedido_id);
CREATE INDEX IF NOT EXISTS idx_item_pedido_produto ON item_pedido(produto_id);
CREATE INDEX IF NOT EXISTS idx_item_pedido_status ON item_pedido(status);
CREATE INDEX IF NOT EXISTS idx_item_pedido_status_pedido ON item_pedido(status, pedido_id);